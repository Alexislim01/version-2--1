import assert from 'node:assert/strict';
import {readFileSync} from 'node:fs';
import {areas,calendarCSV,decodeFinal,finalCalendar,pointCSV,pointInArea,type FinalManifest,type FinalPoint,type Layer} from '../frontend/src/final-model.ts';
import {parseCSV} from '../frontend/src/engine.ts';

const root=new URL('../frontend/public/data/final/',import.meta.url);
const manifest:FinalManifest=JSON.parse(readFileSync(new URL('manifest.json',root),'utf8'));
const points:FinalPoint[]=manifest.shards.flatMap(shard=>{const block=JSON.parse(readFileSync(new URL(shard.url,root),'utf8'));return (['modis','viirs','synthetic'] as Layer[]).flatMap(layer=>{assert.equal(block[layer].length,shard.counts[layer]);return decodeFinal(block[layer],layer);});});
assert.equal(manifest.calendar.length,216);
assert.equal(points.length,363842);
assert.equal(points.filter(p=>p.layer==='viirs').length,144253);
const national=finalCalendar(manifest,points,areas[0],'all');
assert.deepEqual(national.map(({year,month,value,source,median,anomaly_pct})=>({year,month,value,source,median,anomaly_pct})),manifest.calendar);
for(const row of national.filter(r=>r.source.startsWith('observed')))assert.equal(row.points,row.value,'Observed calendar must reconcile to actual detections');
const expected=points.filter(p=>p.layer==='synthetic'&&p.acq_date.startsWith('2003-03')&&p.daynight==='N'&&p.longitude<=105).length;
const regional=finalCalendar(manifest,points,areas[1],'N');
assert.equal(regional.find(r=>r.year===2003&&r.month===3)?.value,expected);
assert.equal(regional.find(r=>r.year===2003&&r.month===3)?.source,'simulated');
assert.equal(regional.find(r=>r.year===2012&&r.month===1)?.source,'observed_partial');
const january=regional.filter(r=>r.month===1&&r.year!==2012).map(r=>r.value).sort((a,b)=>a-b);
assert.equal(regional.find(r=>r.month===1)?.median,january[8],'Partial January cannot enter the baseline');
const blank={id:'custom',label:'Outside country',bbox:[-5,-5,5,5]};
assert(finalCalendar(manifest,points,blank,'all').every(r=>r.value===0&&r.anomaly_pct===null));
const point=points.find(p=>p.layer==='synthetic')!;
assert.equal(point.is_synthetic,true);assert(['paired','hole'].includes(point.sim_source));assert.equal(point.sim_run,1);
const shape={type:'Polygon' as const,coordinates:[[[99,0],[120,0],[120,9],[99,9],[99,0]],[[point.longitude-.01,point.latitude-.01],[point.longitude+.01,point.latitude-.01],[point.longitude+.01,point.latitude+.01],[point.longitude-.01,point.latitude+.01],[point.longitude-.01,point.latitude-.01]]]};
assert.equal(pointInArea(point,{id:'custom',label:'Hole',bbox:[99,0,120,9],shape}),false);
const csv=pointCSV([point]);assert(csv.includes('SIM1.0'));assert(csv.includes('is_synthetic,sim_source,sim_parent_modis,sim_run'));assert(csv.includes(point.sim_parent_modis));
assert.throws(()=>parseCSV(csv),/simulated detections/,'Legacy imports must never silently turn synthetic points into observations');
assert(calendarCSV(regional).includes('simulated'));
console.log('PASS national source parity, observed reconciliation, scope/night filtering, partial baselines, empty coverage, polygon holes, and synthetic export/import separation');
